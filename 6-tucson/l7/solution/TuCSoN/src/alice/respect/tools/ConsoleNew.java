private void loadSpecificationButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loadSpecificationButtonActionPerformed
    JFileChooser choose = new JFileChooser();
    int returnVal = choose.showOpenDialog(this);
    if (returnVal == javax.swing.JFileChooser.APPROVE_OPTION) {
        File file = choose.getSelectedFile();
        //This is where a real application would open the file.
        this.outputTextArea.append("Opening: " + file.getName() + ".\n");
        String spec = this.readFile(file);

        try{
        	managementContext = RespectTCContainer.getRespectTCContainer().getManagementContext(new TupleCentreId(this.tupleCentreComboBox.getSelectedItem()+"@localhost"));
            managementContext.setSpec(new RespectSpecification(spec));
            outputTextArea.append("Specification loading: OK \n");
        }catch(Exception e){
            e.printStackTrace();
            outputTextArea.append("Specification loading: failed \n");
        }
            //output.append(this.readFile(file));
    } else {
        outputTextArea.append("Open command cancelled by user.\n");
    }
}//GEN-LAST:event_loadSpecificationButtonActionPerformed

