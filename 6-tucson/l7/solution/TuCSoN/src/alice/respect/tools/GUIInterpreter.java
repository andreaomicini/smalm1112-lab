    class ProcessInput extends Thread {
        ProcessInput(GUIInterpreter agent){
            this.agent=agent;
           
        }

        
        public void run(){
            try {
                agent.input.setEditable(false);

                String cmd=agent.input.getText();
                if (cmd.equals("quit")){
                    exitForm(null);
                } else {
                    int index1=cmd.indexOf('(');
                    int index2=cmd.lastIndexOf(')');

                    if (index1!=-1 && index2!=-1){
                        String methodName=removeSpaces(cmd.substring(0,index1));
                        String tuple=cmd.substring(index1+1,index2);
                        if (methodName.equals("out")){
                            LogicTuple t=LogicTuple.parse(tuple);
                            context.out(id,t);
                            agent.output.append("ok.\n");
                        } else if (methodName.equals("in")){
                            LogicTuple templ=LogicTuple.parse(tuple);
                            agent.output.append("waiting for tuple: ... "+tuple+"\n");
                            LogicTuple t = context.in(id,templ);
                            if (t==null){
                                agent.output.append("answer: no\n");
                            } else {
                                agent.output.append("answer: "+t+"\n");
                            }
                        } else if (methodName.equals("rd")){
                            LogicTuple templ=LogicTuple.parse(tuple);
                            agent.output.append("waiting for tuple: ... "+tuple+"\n");
                            LogicTuple t = context.rd(id,templ);
                            if (t==null){
                                agent.output.append("answer: no\n");
                            } else {
                                agent.output.append("answer: "+t+"\n");
                            }
                        } else if (methodName.equals("inp")){
                            LogicTuple templ=LogicTuple.parse(tuple);
                            LogicTuple t = context.inp(id,templ);
                            if (t==null){
                                agent.output.append("answer: no\n");
                            } else {
                                agent.output.append("answer: "+t+"\n");
                            }
                        } else if (methodName.equals("rdp")){
                            LogicTuple templ=LogicTuple.parse(tuple);
                            LogicTuple t = context.rdp(id,templ);
                            if (t==null){
                                agent.output.append("answer: no\n");
                            } else {
                                agent.output.append("answer: "+t+"\n");
                            }
                        } else if (methodName.equals("set_spec")){
                            if (tuple.startsWith("'")){
                                tuple=tuple.substring(1,tuple.length()-1);
                            }
                            mContext.setSpec(new RespectSpecification(tuple));
                            agent.output.append("ok"+"\n");
                        } else if (methodName.equals("get_spec")){
                            RespectSpecification spec = mContext.getSpec();
                            agent.output.append("answer: "+spec+"\n");
                        } else {
                            agent.output.append("unknown operation: "+methodName+"\n");
                        }
                    }  else {
                        agent.output.append("syntax error in "+cmd+"\n");
                    }
                }
            } catch (InvalidSpecificationException ex){
                //output.append(ex.toString()+"\n");
                agent.output.append("invalid ReSpecT specification.\n");
            } catch (InvalidLogicTupleException ex){
                //output.append(ex.toString()+"\n");
                agent.output.append("syntax error in logic tuple description.\n");
            } catch (Exception ex){
                //output.append(ex.toString()+"\n");
                agent.input.setEditable(true);
                agent.output.append("error.\n");
            }
            answerScrollPane.getVerticalScrollBar().setValue(answerScrollPane.getVerticalScrollBar().getMaximum());
            agent.input.setEditable(true);

        }
        GUIInterpreter agent;
    }
