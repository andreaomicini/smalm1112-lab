  private void inputActionPerformed (java.awt.event.ActionEvent evt) {//GEN-FIRST:event_inputActionPerformed
    
	  if(evt.getActionCommand()=="specification"){
		  int returnVal = choose.showOpenDialog(this);

	        if (returnVal == javax.swing.JFileChooser.APPROVE_OPTION) {
	            File file = choose.getSelectedFile();
	            //This is where a real application would open the file.
	            output.append("Opening: " + file.getName() + ".\n");
	            String spec = this.readFile(file);
	            
	            try{
	            	mContext.setSpec(new RespectSpecification(spec));
	            	output.append("Specification loading: OK \n");
	            }catch(Exception e){
	                e.printStackTrace();
	                output.append("Specification loading: failed \n");
	            }
	            	//output.append(this.readFile(file));
	        } else {
	            output.append("Open command cancelled by user.\n");
	        }
	  }else{
		  new ProcessInput(this).start();
	  }
  }//GEN-LAST:event_inputActionPerformed


  private String readFile(File f) {
	  
	  String output = "";
	  try {
		BufferedReader br = new BufferedReader(new FileReader(f));
		String line = br.readLine();
		//System.out.println("line1: "+line);
		while(line!=null){
			
			output += line + " \n";
			line = br.readLine();
			
		}
		
		br.close();
		
		
	} catch (Exception e) {
		// TODO Auto-generated catch block
		return e.getMessage();
	}
	  
	return output;
	  
  }
    private String removeSpaces(String st){
        int i=0;
        int j=st.length()-1;
        while (st.charAt(i)==' ') i++;
        while (st.charAt(j)==' ') j--;
        return st.substring(i,j+1);
    }

