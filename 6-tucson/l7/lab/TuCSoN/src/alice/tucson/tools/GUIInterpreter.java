	class ProcessInput extends Thread
	{
		
		ProcessInput(GUIInterpreter agent)
		{
			//neew: bugs fix
			String st_aid = "cli" + System.currentTimeMillis();  
			try {
				context = Tucson.getContext(new TucsonAgentId(st_aid), TucsonAgentLanguageManager.getCurLanguage());
			} catch (ContextNotAvailableException e) {
				// TODO Auto-generated catch block
				e.printStackTrace();
			} catch (TucsonInvalidAgentIdException e) {
				// TODO Auto-generated catch block
				e.printStackTrace();
			} 											// fin qui: new
			this.agent = agent;
		}

		public void run()
		{
			try
			{
				agent.input.setEditable(false);

				String st = agent.input.getText();
				String hostName = "localhost";
				String tcName = "default";
				int index3 = st.indexOf('?');
				int index4 = st.indexOf('@');

				String cmd = st.substring(index3 + 1, st.length());								
				
				if (cmd.equals("quit"))
				{
					context.exit();
					exitForm(null);
				}
				else
				{
					int index1 = cmd.indexOf('(');
					int index2 = cmd.lastIndexOf(')');

					hostName = "localhost";	
					if (index4 != -1 && index3 != -1)
					{
						hostName = st.substring(index4 + 1, index3);
					}

					tcName = "default"; 
					if (index3 != -1)
					{
						if (index4 != -1)
						{
							tcName = st.substring(0, index4);
						}
						else
						{
							tcName = st.substring(0, index3);
						}
					}

					hostName = removeSpaces(hostName);
					tcName = removeSpaces(tcName);
					TucsonTupleCentreId tid = new TucsonTupleCentreId(tcName + "@" + hostName);										

					if (index1 != -1 && index2 != -1)
					{
						String methodName = removeSpaces(cmd.substring(0, index1));
						String tuple = cmd.substring(index1 + 1, index2);
						
						if (methodName.equals("out"))
						{							
							LogicTuple t = LogicTuple.parse(tuple);
							context.out(tid, t, (Long) null);  
							agent.output.append("ok.\n");
							
						}
						else if (methodName.equals("in"))
						{
							LogicTuple templ = LogicTuple.parse(tuple);
							agent.output.append("waiting for tuple: ... " + tuple + "\n");
							LogicTuple t = (LogicTuple) context.in(tid, templ, (Long) null);
							
							if (t == null)
							{
								agent.output.append("answer: no\n");
							}
							else
							{
								agent.output.append("answer: " + t + "\n");
							}
						}
						else if (methodName.equals("rd"))
						{
							LogicTuple templ = LogicTuple.parse(tuple);
							agent.output.append("waiting for tuple: ... " + tuple + "\n");
							LogicTuple t = (LogicTuple) context.rd(tid, templ, (Long) null);
							
							if (t == null)
							{
								agent.output.append("answer: no\n");
							}
							else
							{
								agent.output.append("answer: " + t + "\n");
							}
						}
						else if (methodName.equals("inp"))
						{
							LogicTuple templ = LogicTuple.parse(tuple);
							LogicTuple t = (LogicTuple) context.inp(tid, templ, (Long) null);
							
							if (t == null)
							{
								agent.output.append("answer: no\n");
							}
							else
							{
								agent.output.append("answer: " + t + "\n");
							}
						}
						else if (methodName.equals("rdp"))
						{
							LogicTuple templ = LogicTuple.parse(tuple);
							LogicTuple t = (LogicTuple) context.rdp(tid, templ, (Long) null);
							
							if (t == null)
							{
								agent.output.append("answer: no\n");
							}
							else
							{
								agent.output.append("answer: " + t + "\n");
							}
						}
						else if(methodName.equals("get"))
						{
							//LogicTuple templ = LogicTuple.parse(tuple);
							agent.output.append("waiting for tuple: ... " + tuple + "\n");
							List<LogicTuple> tl = context.get(tid, (Long) null);
							String res="[";
							for(LogicTuple t :tl)
							{
								res+=t+",";
							}
							res=res.substring(0, res.lastIndexOf(","))+"]";
							agent.output.append(res+"\n");
						}
						else if (methodName.equals("set_spec"))
						{
							if (tuple.startsWith("'"))
							{
								tuple = tuple.substring(1, tuple.length() - 1);
							}
							//System.out.println(tuple);
							context.setSpec(tid, tuple, (Long) null);
							agent.output.append("ok" + "\n");
						}
						else if (methodName.equals("get_spec"))
						{
							String spec = (String) context.getSpec(tid, (Long) null);
							agent.output.append("answer: " + spec + "\n");
						}
						else if (methodName.equals("out_s"))
						{
							LogicTuple t = LogicTuple.parse(tuple);
							context.out_s(tid, t, (Long) null);
							agent.output.append("ok.\n");
						}
						else if (methodName.equals("in_s"))
						{
							LogicTuple templ = LogicTuple.parse(tuple);
							agent.output.append("waiting for tuple: ... " + tuple + "\n");
							LogicTuple t = (LogicTuple) context.in_s(tid, templ, (Long) null);
							
							if (t == null)
							{
								agent.output.append("answer: no\n");
							}
							else
							{
								agent.output.append("answer: " + t + "\n");
							}
						}
						else if (methodName.equals("rd_s"))
						{
							LogicTuple templ = LogicTuple.parse(tuple);
							agent.output.append("waiting for tuple: ... " + tuple + "\n");
							LogicTuple t = (LogicTuple) context.rd_s(tid, templ, (Long) null);
							if (t == null)
							{
								agent.output.append("answer: no\n");
							}
							else
							{
								agent.output.append("answer: " + t + "\n");
							}
						}
						else if (methodName.equals("inp_s"))
						{
							LogicTuple templ = LogicTuple.parse(tuple);
							LogicTuple t = (LogicTuple) context.inp_s(tid, templ, (Long) null);
							if (t == null)
							{
								agent.output.append("answer: no\n");
							}
							else
							{
								agent.output.append("answer: " + t + "\n");
							}
						}
						else if (methodName.equals("rdp_s"))
						{
							LogicTuple templ = LogicTuple.parse(tuple);
							LogicTuple t = (LogicTuple) context.rdp_s(tid, templ, (Long) null);
							if (t == null)
							{
								agent.output.append("answer: no\n");
							}
							else
							{
								agent.output.append("answer: " + t + "\n");
							}
						}
						else
						{
							agent.output.append("unknown communication act: " + methodName + "\n");
						}
					}
					else
					{
						agent.output.append("syntax error in " + st + "\n");
					}
				}
			}
			catch (InvalidLogicTupleException ex)
			{
				// output.append(ex.toString()+"\n");
				agent.output.append("syntax error in logic tuple description.\n");
			}
			catch (Exception ex)
			{
				ex.printStackTrace();
				// output.append(ex.toString()+"\n");
				agent.input.setEditable(true);
				agent.output.append("error.\n");
			}
			answerScrollPane.getVerticalScrollBar().setValue(answerScrollPane.getVerticalScrollBar().getMaximum());
			agent.input.setEditable(true);
		}

		GUIInterpreter agent;
	}
